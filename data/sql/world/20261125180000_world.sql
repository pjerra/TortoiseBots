-- Level-60 enchant choice per spec and slot, read from the common Forever player picks.
--
-- Source: aotc.gg (official WoW Forever armory), 2026-11-24 sample of level-60 characters, `best_geared`
-- population (the top-geared characters, the closest match to a level-60 bot's gear). For each class spec and
-- equipment slot: when at least 60% of those characters carry no enchant in the slot, the slot is left empty
-- (`spellid` 0); otherwise the most used non-empty enchant is the spec's choice. A bot at level 60 uses this row
-- instead of the generic candidate scoring, so it ends up with what Forever players actually run and does not
-- show an enchant on a slot players leave empty. Below 60 nothing changes; the data only covers level 60.
--
-- `spec_id` is `ai_playerbot_weightscales.id` (druid feral maps to two ids, feraltank and feraldps).
-- `slotid` is the core EquipmentSlots value. `item_id` and `none_pct` are the armory evidence for the row and are
-- not read at runtime; `spellid` is the enchant spell id (`EnchantItemT`'s argument), not a SpellItemEnchantment id.
--
-- Rows are keyed by spec+slot only; the selector still checks the item's class/subclass/inventory-type mask and the
-- existing level and quality bands, so a slot the spec table names never receives an enchant the item cannot take.
--
-- Idempotent: DELETE + INSERT.
CREATE TABLE IF NOT EXISTS `ai_playerbot_spec_enchant` (
  `spec_id`   tinyint unsigned NOT NULL,
  `slotid`    tinyint unsigned NOT NULL,
  `spellid`   mediumint unsigned NOT NULL DEFAULT 0,
  `item_id`   mediumint unsigned NOT NULL DEFAULT 0,
  `none_pct`  decimal(4,1) unsigned NOT NULL DEFAULT 0.0,
  `name`      varchar(255) NOT NULL DEFAULT '',
  PRIMARY KEY (`spec_id`, `slotid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3;

