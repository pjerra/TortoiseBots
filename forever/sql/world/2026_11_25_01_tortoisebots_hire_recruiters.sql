-- One recruiter per Forever inn, two and a half yards to the innkeeper's left, cloned from the innkeeper
-- (opposite-gender display and a new first name where the 1.18 display set has one, exactly as TortoiseBots
-- ships them). The 44 inns TortoiseBots already covers keep their TB entry (1000000 + TB entry - 95000) and
-- display; the 11 Forever-only inns (Riverglades, Zephras Isle, Shen'dralas, Mount Hyjal, Talrendis Point,
-- Kargath) get 1000041-1000045 and 1000049-1000054. Recruiter ids stay below 1000070; 1000070-1000071 are the
-- world-buff kill-credit creatures below, and the hire-contract credits (1000080+) belong to the tier package.
--
-- Spawn spots are 2.5 yd left of the innkeeper (r3 spot table), zoneId/areaId filled from this server's
-- area ids; the Forever-only zones have no sub-area row yet, so their areaId is the zone id.
-- ScriptName is the CreatureAI this package registers (forever/src/host/hire/TbHireRecruiter.cpp).
-- Greetings: npc_text in this database; their broadcast_text rows are in
-- forever/sql/hotfixes/2026_11_25_02_tortoisebots_hire_recruiter_text.sql (Forever keeps broadcast_text there).
--
-- 1000070-1000071 are the world-buff kill-credit creatures (never spawned, invisible display); the hire-contract
-- credits 1000080+ belong to the tier package and are not here.
--
-- A viewer's npcflags do not carry GOSSIP|QUESTGIVER while the creature has neither a runtime gossip menu nor one
-- assigned in creature_template_gossip, so every recruiter gets menu id = its entry and the greeting text behind it
-- (the AI builds the real menu and its OnGossipHello answers first; these rows only keep the flags visible).
--
-- Idempotent: every row this file owns is deleted first: entries 1000000-1000054 and 1000070-1000071, spawn
-- guids 4000000-4000054, npc_text 1000000-1000054 and 1000100-1000154, gossip_menu and creature_template_gossip
-- 1000000-1000054.

