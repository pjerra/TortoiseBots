-- The level-60 enchant choice per class, spec and equipment slot, from the common Forever player picks.
--
-- Source: aotc.gg (the official WoW Forever armory), 2026-11-24 sample of level-60 characters, `best_geared`
-- population (the top-geared characters, the closest match to a level-60 bot's gear). For each spec and equipment
-- slot: when at least 60% of those characters carry no enchant in the slot, the slot is left empty (`spellid` 0);
-- otherwise the most used non-empty enchant is the spec's choice. A level-60 bot wears that choice instead of the
-- generic pick, and a slot players leave empty stays empty. Below 60 nothing changes: the sample covers 60 only.
--
-- `class_id` and `spec_name` are the core class id and the canonical weight-scale spec name
-- (`ai_playerbot_weightscales.name`, which is also `GearSetOutcome::specName`: "arms", "prot", "feraltank", ...);
-- the same name exists for two classes and for a druid's two feral scales, so the class is part of the key.
-- `slotid` is the core EquipmentSlots value. `min_level` is the choice's own level requirement (its
-- `ai_playerbot_enchant_candidates` row where the Turtle data has one, 60 for the level-60-only Forever
-- enchantments); the reader applies the ordinary item-quality band on it (white 10, green 5, blue and better 0)
-- and never puts the choice on grey gear.
-- `item_id` and `none_pct` are the armory evidence for the row and are not read at runtime; `spellid` is the
-- enchant spell id (the spell cast on the item, not a SpellItemEnchantment id).
--
-- Idempotent: CREATE IF NOT EXISTS, then DELETE + INSERT in one transaction.
