#!/usr/bin/env python3
"""Write forever/sql/world/2026_11_25_01_tortoisebots_hire_gear.sql from the committed hire-gear data.

Inputs (read-only, both committed):
  tools/hire_gear/data/hire_gear.csv            TortoiseBots' 0-based tier sets, one row per class+spec+race+tier+slot
  forever/data/waterys/gear-replacements.csv    the same rows mapped onto Forever item ids by forever/data/waterys/gear-rule.md

Rules (forever/docs/HIRE-P4-NOTES.md):
  * tiers 1-6 only: TB tier 7 is the Tower of Karazhan raid, which does not exist on Forever;
  * the shaman "tank" spec row is Turtle-only and has no Forever spec tab, so its rows are dropped;
  * a row the replacement file maps to the same id is kept, a substituted row keeps the substitute, and TB's
    item 0 rows (clear the slot for a two-handed set) are kept as item 0;
  * race is TB's: 0 is the generic row, a race-specific row wins at equip time;
  * no enchant column: TB's enchant ids are mostly TBC/WotLK spell ids and only 7 of 84 are proven on Forever.

Usage: python3 forever/tools/gen_hire_tiers.py            (writes the file)
       python3 forever/tools/gen_hire_tiers.py --check    (fails when the file would change)
"""
import argparse
import csv
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TB_CSV = os.path.join(ROOT, "tools", "hire_gear", "data", "hire_gear.csv")
MAP_CSV = os.path.join(ROOT, "forever", "data", "waterys", "gear-replacements.csv")
OUT = os.path.join(ROOT, "forever", "sql", "world", "2026_11_25_01_tortoisebots_hire_gear.sql")

TIERS = range(1, 7)


def rows():
    tb = list(csv.DictReader(open(TB_CSV, encoding="utf-8")))
    mapped = list(csv.DictReader(open(MAP_CSV, encoding="utf-8")))
    by_key = defaultdict(list)
    for row in mapped:
        by_key[(row["class"], row["spec"], row["tier"], row["slot"])].append(row)

    out = []
    for row in tb:
        tier = int(row["tier"])
        if tier not in TIERS:
            continue
        if row["class"] == "7" and row["spec"] == "tank":
            continue
        key = (row["class"], row["spec"], row["tier"], row["slot"])
        candidates = by_key.get(key)
        if not candidates:
            if row["item_id"] != "0":
                raise SystemExit("no Forever mapping for %s/%s tier %s slot %s (TB item %s)"
                                 % (row["class"], row["spec"], row["tier"], row["slot"], row["item_id"]))
            item = 0
        elif len(candidates) == 1:
            item = int(candidates[0]["forever_id"])
        else:
            # The mapping file dropped TB's race column, so the race variants collide on the key. The item
            # name is unique per key (both mapping rows are unsubstituted), so match on it.
            pick = next((c for c in candidates if c["name"] == row["item_name"]), None)
            if pick is None:
                raise SystemExit("ambiguous Forever mapping for %s/%s tier %s slot %s"
                                 % (row["class"], row["spec"], row["tier"], row["slot"]))
            item = int(pick["forever_id"])
        out.append((int(row["class"]), row["spec"], int(row["race"]), tier, int(row["slot"]), item))

    out.sort()
    keys = {(r[0], r[1], r[2], r[3], r[4]) for r in out}
    if len(keys) != len(out):
        raise SystemExit("duplicate class/spec/race/tier/slot key in the generated rows")
    expected_keys = {(int(r["class"]), r["spec"]) for r in tb
                     if int(r["tier"]) in TIERS and not (r["class"] == "7" and r["spec"] == "tank")}
    if len(expected_keys) != 28:
        raise SystemExit("expected 28 spec keys, got %d" % len(expected_keys))
    return out


def render(rows):
    lines = [
        "-- Hire gear tiers 1-6 on Forever items: the static level-60 sets a companion is hired with",
        "-- (TbHireTiers.cpp; TB parity minus Turtle-only content: no tier 7 Tower of Karazhan, no shaman tank spec).",
        "--",
        "-- GENERATED by forever/tools/gen_hire_tiers.py from tools/hire_gear/data/hire_gear.csv and",
        "-- forever/data/waterys/gear-replacements.csv (the Forever-id mapping of forever/data/waterys/gear-rule.md).",
        "-- Never edit the rows by hand: fix the inputs and regenerate. Gaps are intentional: a slot without a row",
        "-- keeps the levelled kit's item, item 0 clears the slot (a two-handed set's off hand).",
        "--",
        "-- `flags` and `source` from TB's table are generator provenance and are not read at runtime, so they are not",
        "-- carried here; `enchant_spell` is dropped too (TB's ids are mostly not Forever spells, see HIRE-P4-NOTES.md).",
        "-- Idempotent: CREATE IF NOT EXISTS, then DELETE the module's own tier range and INSERT.",
        "CREATE TABLE IF NOT EXISTS `tortoise_bots_hire_gear` (",
        "  `class` tinyint unsigned NOT NULL,",
        "  `spec` varchar(16) NOT NULL,",
        "  `race` tinyint unsigned NOT NULL DEFAULT 0,",
        "  `tier` tinyint unsigned NOT NULL,",
        "  `slot` tinyint unsigned NOT NULL,",
        "  `item_id` int unsigned NOT NULL DEFAULT 0,",
        "  PRIMARY KEY (`class`, `spec`, `race`, `tier`, `slot`)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb3;",
        "",
        "DELETE FROM `tortoise_bots_hire_gear` WHERE `tier` BETWEEN 1 AND 6;",
        "INSERT INTO `tortoise_bots_hire_gear` (`class`, `spec`, `race`, `tier`, `slot`, `item_id`) VALUES",
    ]
    body = []
    for i, (cls, spec, race, tier, slot, item) in enumerate(rows):
        body.append("(%d,'%s',%d,%d,%d,%d)" % (cls, spec, race, tier, slot, item))
    # One statement per ~400 rows keeps a mysqldump-sized file readable without one giant line.
    for start in range(0, len(body), 400):
        chunk = body[start:start + 400]
        last = start + len(chunk) == len(body)
        joined = ",\n".join(chunk)
        lines.append(joined + (";" if last else ","))
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the committed file differs")
    args = parser.parse_args()

    data = rows()
    text = render(data)
    if args.check:
        if not os.path.exists(OUT):
            raise SystemExit("missing " + OUT)
        if open(OUT, encoding="utf-8").read() != text:
            raise SystemExit("stale " + OUT + ": run python3 forever/tools/gen_hire_tiers.py")
        print("OK: hire gear SQL is up to date (%d rows)" % len(data))
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s: %d rows" % (os.path.relpath(OUT, ROOT), len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
