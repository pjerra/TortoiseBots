#!/usr/bin/env python3
"""List the fields of `struct Facts` (runtime/DungeonRunPolicy.h) in declaration order.

    python3 forever/tools/facts_fields.py            # one line per field: name, line, declared type
    python3 forever/tools/facts_fields.py --inc F    # also write F as a C++ include for the access tracer
                                                     #   (FIELD(name) per field, in declaration order)

Used by forever/tools/facts_trace.cpp and forever/tools/facts_reads.py (R0 of slice S5, forever/docs/RUN-S5-FACTS-RFC.md).
The field count is checked against runtime/DecisionCaptureFields.gen.h (the generated list of the same struct).
"""
import os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
HEADER = os.path.join(ROOT, "runtime", "DungeonRunPolicy.h")
GEN = os.path.join(ROOT, "runtime", "DecisionCaptureFields.gen.h")


def split_top(text, sep):
    """Split on `sep` outside (), {}, [] and the angle brackets of a template."""
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "({[<":
            depth += 1
        elif ch in ")}]>":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return parts


def fields():
    lines = open(HEADER, encoding="utf-8", errors="replace").read().split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith("struct Facts"))
    end = next(i for i in range(start, len(lines)) if lines[i].startswith("};"))
    out = []
    # (line number, text without comments); a declaration may span lines: join until its `;`
    buf, first = "", None
    for i in range(start + 2, end):
        code = re.sub(r"//.*", "", lines[i])
        if not code.strip():
            continue
        if first is None:
            first = i + 1
        buf += " " + code.strip()
        if code.rstrip().endswith(";") and buf.count("{") == buf.count("}") and buf.count("(") == buf.count(")"):
            decl = buf.strip().rstrip(";")
            segs = split_top(decl, ",")
            head = re.split(r"\s*(?:=|\{)", segs[0], 1)[0]
            m = re.match(r"(.*?)([A-Za-z_]\w*)(?:\[[^\]]*\])?$", head.strip())
            if not m: print("BAD", repr(decl), file=sys.stderr)
            typ, name = m.group(1).strip(), m.group(2)
            out.append((name, first, typ))
            for seg in segs[1:]:
                n = re.match(r"\s*([A-Za-z_]\w*)", seg).group(1)
                out.append((n, first, typ))
            buf, first = "", None
    return out


def main():
    fs = fields()
    gen = open(GEN).read()
    m = re.search(r"#define TB_DCAP_FIELDS_Facts\(X\)(.*)", gen)
    gen_names = re.findall(r"X\((\w+)\)", m.group(1))
    names = [f[0] for f in fs]
    # the generated list leaves out a std::function (pointLiquid), see its header comment
    miss = [n for n in names if n not in gen_names]
    extra = [n for n in gen_names if n not in names]
    print(f"# fields {len(fs)} (generated list: {len(gen_names)}; only here: {miss}; only there: {extra})", file=sys.stderr)
    if "--inc" in sys.argv:
        path = sys.argv[sys.argv.index("--inc") + 1]
        with open(path, "w") as o:
            o.write("// Generated by forever/tools/facts_fields.py. One FIELD(name, line) per member of Facts, declaration order.\n")
            for n, ln, t in fs:
                o.write(f"FIELD({n}, {ln})\n")
    else:
        for n, ln, t in fs:
            print(f"{n}\t{ln}\t{t}")


if __name__ == "__main__":
    main()
