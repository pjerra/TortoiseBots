#!/usr/bin/env python3
"""Generate forever/conf/aiplayerbot.conf.dist from the Get*Default calls of ai/playerbot/PlayerbotAIConfig.cpp.

    python3 forever/tools/gen_aiplayerbot_conf.py            # write the file
    python3 forever/tools/gen_aiplayerbot_conf.py --check    # exit 1 when the file is not what the source gives

Every `config.Get{Bool,Int,Float,String}Default("Key", default)` call is one entry: the key, the default the code has, and its
type. A call whose default is not a literal (an expression, a variable read earlier) is written commented out with the
expression: the code's own default applies when the key is absent, so such a key is left for the owner to set. A key read
more than once is written once (the first call); a later call with a different default is noted in a comment. Calls whose key
is not a string literal are counted in the header, not listed. The file is read by TbCompat_Config (ACE ini rules: one section,
`#` comments on their own line, `key = value`), see forever/docs/SLICE1-R4C-NOTES.md.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SOURCE = os.path.join(ROOT, "ai", "playerbot", "PlayerbotAIConfig.cpp")
OUT = os.path.join(ROOT, "forever", "conf", "aiplayerbot.conf.dist")

CALL = re.compile(r"\bconfig\.Get(Bool|Int|Float|String)Default\s*\(")


def split_args(text, start):
    """Arguments of the call whose '(' is just before `start`: (list of argument texts, index after the ')')."""
    depth, i, args, cur = 1, start, [], []
    in_str = None
    while i < len(text):
        c = text[i]
        if in_str:
            cur.append(c)
            if c == "\\":
                i += 1
                cur.append(text[i])
            elif c == in_str:
                in_str = None
        elif c in "\"'":
            in_str = c
            cur.append(c)
        elif c in "([{":
            depth += 1
            cur.append(c)
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                args.append("".join(cur).strip())
                return args, i + 1
            cur.append(c)
        elif c == "," and depth == 1:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    raise ValueError("unbalanced call")


def literal(kind, expr):
    """The conf text of a literal default, or None when the default is an expression."""
    e = expr.strip()
    if kind == "Bool":
        return {"true": "1", "false": "0"}.get(e)
    if kind == "Int":
        m = re.fullmatch(r"\(?\s*(?:u?int(?:8|16|32|64)(?:_t)?|int|unsigned|long)?\s*\)?\s*(-?\d+)[uUlL]*", e)
        if m:
            return m.group(1)
        # integer arithmetic of plain numbers (6 * 3600)
        if re.fullmatch(r"[\d\s\*\+\-\(\)]+", e) and re.search(r"\d", e):
            try:
                return str(int(eval(e, {"__builtins__": {}}, {})))
            except Exception:
                return None
        return None
    if kind == "Float":
        m = re.fullmatch(r"(-?\d+(?:\.\d*)?|-?\.\d+)[fF]?", e)
        if not m:
            return None
        v = m.group(1)
        return v if "." in v else v + ".0"
    if kind == "String":
        if e in ('""', "std::string()", "std::string(\"\")"):
            return ""
        # one string literal or several side by side ("a" "b")
        if re.fullmatch(r'(?:"(?:[^"\\]|\\.)*"\s*)+', e):
            text = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', e))
            if "\\" not in text:
                return text
    return None


def collect(text):
    entries, order, nonliteral_keys = {}, [], 0
    for m in CALL.finditer(text):
        kind = m.group(1)
        args, _ = split_args(text, m.end())
        line = text.count("\n", 0, m.start()) + 1
        if not args or not re.fullmatch(r'"[^"\\]+"', args[0]):
            nonliteral_keys += 1
            continue
        key = args[0][1:-1]
        default = args[-1] if len(args) >= 2 else ""
        lit = literal(kind, default)
        entry = (kind, key, lit, default, line)
        if key in entries:
            first = entries[key]
            if (first["lit"], first["kind"]) != (lit, kind):
                first["notes"].append("line %d reads it as %s with default %s" % (line, kind, default))
            continue
        entries[key] = {"kind": kind, "lit": lit, "expr": default, "line": line, "notes": []}
        order.append(key)
    return entries, order, nonliteral_keys


def render(entries, order, nonliteral_keys):
    out = []
    out.append("# TortoiseBots bot engine configuration (aiplayerbot.conf).")
    out.append("# GENERATED by forever/tools/gen_aiplayerbot_conf.py from the Get*Default calls of ai/playerbot/PlayerbotAIConfig.cpp:")
    out.append("# do not edit by hand, run the tool. Every uncommented line is a key with the default the code has; a commented line is a")
    out.append("# key whose default the code computes, so it is left to the code until it is set here.")
    out.append("# Install as aiplayerbot.conf in the directory that holds worldserver.conf (see forever/docs/SLICE1-R4C-NOTES.md).")
    out.append("# %d keys, %d with a literal default, %d computed; %d reads with a non-literal key are not listed."
               % (len(order), sum(1 for k in order if entries[k]["lit"] is not None),
                  sum(1 for k in order if entries[k]["lit"] is None), nonliteral_keys))
    out.append("")
    out.append("[AiPlayerbotConf]")
    out.append("")
    for key in order:
        e = entries[key]
        out.append("# %s  (%s, PlayerbotAIConfig.cpp:%d)" % (key, e["kind"].lower(), e["line"]))
        for note in e["notes"]:
            out.append("#   note: " + note)
        if e["lit"] is None:
            out.append("#   default is computed in the code: %s" % " ".join(e["expr"].split()))
            out.append("# %s =" % key)
        else:
            out.append("%s = %s" % (key, e["lit"]))
        out.append("")
    return "\n".join(out)


def main():
    text = open(SOURCE, encoding="utf-8", errors="replace").read()
    entries, order, nonliteral_keys = collect(text)
    rendered = render(entries, order, nonliteral_keys)
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != rendered:
            print("aiplayerbot.conf.dist is out of step with PlayerbotAIConfig.cpp: run forever/tools/gen_aiplayerbot_conf.py")
            return 1
        print("aiplayerbot.conf.dist matches (%d keys)" % len(order))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(rendered)
    lit = sum(1 for k in order if entries[k]["lit"] is not None)
    print("wrote %s: %d keys, %d literal, %d computed, %d non-literal-key reads skipped" % (OUT, len(order), lit, len(order) - lit, nonliteral_keys))
    return 0


sys.exit(main())
