// Access log of the run leader's `Facts` on a simulated Ragefire Chasm run (R0 of slice S5, forever/docs/RUN-S5-FACTS-RFC.md).
//
//   facts_trace <rows.tsv> <fields.inc> <out.tsv> [ticks]
//
// Builds the RFC plan from the exported rows (forever/tools/facts_rfc.py writes rows.tsv from the SQL files, the loader's own table API
// takes them), then calls DungeonRun::Tick once a second on a Facts object that lives in pages of its own. The pages are
// protected for the call: every first read of a field's bytes faults, the SIGSEGV handler records (field, instruction, return
// chain, step kind, phase), lets that one instruction run (trap flag) and protects the pages again. No policy code is changed: the
// policy sees a const Facts& as it always does. The world is a small scripted model (below): the party walks the plan's points,
// pulls what the pull rows name, kills it, rests, and the boss rows end with the boss dead.
//
// x86-64 Linux only (REG_RIP, trap flag). Build: g++ -std=c++17 -O0 -g -no-pie -fno-omit-frame-pointer.

#include "../../runtime/DungeonRunPolicy.h"

#include <csignal>
