#!/usr/bin/env python3
"""Write forever/compat/: forwarding headers so code written for the Turtle (MaNGOS-family) core finds the
ForeverCore (TrinityCore) header for the same thing under the old include path.

    python3 forever/tools/gen_compat_headers.py <ForeverCore checkout>

Only include *paths* are bridged here. A header whose content has no ForeverCore counterpart (Turtle LFT, the Turtle
module hooks, Lua) is listed in UNMAPPED and gets no file, so the compiler still stops there.
Run it again after moving the core pin; commit the result.
"""
import collections, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "forever", "compat")

# Old include -> ForeverCore header(s) with a different name.
RENAMED = {
    "Database/DBCStores.h": ["DB2Stores.h"], "DBCStores.h": ["DB2Stores.h"],
    "Database/DBCStructure.h": ["DB2Structure.h"], "DBCStructure.h": ["DB2Structure.h"],
    "Database/DBCStore.h": ["DB2Store.h"],
    "Database/SQLStorages.h": ["ObjectMgr.h"],
    "Maps/PathFinder.h": ["PathGenerator.h"],
    "Maps/MoveMap.h": ["MMapManager.h"],
    "Maps/MoveMapSharedDefines.h": ["MMapDefines.h"],
    "Objects/ItemPrototype.h": ["ItemTemplate.h"], "ItemPrototype.h": ["ItemTemplate.h"],
    "Battlegrounds/BattleGroundMgr.h": ["BattlegroundMgr.h"],
    "Battlegrounds/BattleGround.h": ["Battleground.h"],
    "SpellEntry.h": ["SpellInfo.h"], "Spells/SpellEntry.h": ["SpellInfo.h"],
    "Movement/TargetedMovementGenerator.h": ["ChaseMovementGenerator.h", "FollowMovementGenerator.h"],
    "Maps/InstanceData.h": ["InstanceScript.h"],
    "Maps/MapPersistentStateMgr.h": ["InstanceLockMgr.h"],
    "SystemConfig.h": ["GitRevision.h"], "revision.h": ["GitRevision.h"],
}
# No counterpart: the code behind these is rewritten for ForeverCore or switched off.
UNMAPPED = {
    "ScriptObjects.h", "MapNodes/MasterPlayer.h", "LFT/LFTMgr.h", "LFTMgr.h", "Handlers/CharacterCreation.h",
    "CharacterCreation.h", "LuaEngine/LuaEngine.h", "LuaEngine.h", "luaEngine.h", "HeadlessSessionMgr.h",
    "Group/CreatureLinkingMgr.h", "Database/CharacterDatabaseCache.h", "GuildBank/GuildBank.h", "MountManager.hpp",
    "Battlegrounds/BattleGroundWS.h", "Battlegrounds/BattleGroundAB.h", "Battlegrounds/BattleGroundAV.h",
    "Battlegrounds/BattleGroundSV.h", "WaitForAttackStrategy.h",
}
SYSTEM = re.compile(r"^(zlib|sys/|netinet/|arpa/|boost/|std|win|ws2|psapi|direct|unistd|fcntl|netdb|time|float)")
INCLUDE = re.compile(r'^\s*#\s*include\s*([<"])([^>"]+)[>"]', re.M)


def main():
    core = sys.argv[1]
    ours = []
    for d, _, names in os.walk(ROOT):
        rel = os.path.relpath(d, ROOT)
        if rel.startswith((".git", "forever", "tools")):
            continue
        ours += [os.path.join(rel, n) for n in names if n.endswith((".h", ".cpp", ".hpp", ".inl"))]
    our_names = {os.path.basename(p) for p in ours}
    our_paths = {os.path.normpath(p) for p in ours}

    core_headers = collections.defaultdict(list)
    for sub in ("src/server", "src/common"):
        for d, _, names in os.walk(os.path.join(core, sub)):
            for n in names:
                if n.endswith((".h", ".hpp")):
                    core_headers[n].append(os.path.join(d, n))

    wanted = collections.Counter()
    for p in ours:
        text = open(os.path.join(ROOT, p), errors="replace").read()
        for kind, name in INCLUDE.findall(text):
            if os.path.normpath(os.path.join(os.path.dirname(p), name)) in our_paths:
                continue
            if any(q.endswith(os.sep + name) or q == name for q in our_paths):
                continue
            if kind == '"' and os.path.basename(name) in our_names:
                continue
            if kind == "<" and "/" not in name and not name.endswith(".h"):
                continue
            if SYSTEM.match(name):
                continue
            wanted[name] += 1

    written, unmapped, unknown = [], [], []
    for name in sorted(wanted):
        base = os.path.basename(name)
        if name in UNMAPPED:
            unmapped.append(name)
            continue
        if name in RENAMED:
            targets = RENAMED[name]
        elif base in core_headers:
            if name == base:
                continue  # found by the core's own include path
            targets = [base]
        else:
            unknown.append(name)
            continue
        missing = [t for t in targets if t not in core_headers]
        if missing:
            unknown.append(f"{name} (target {missing} not in the core)")
            continue
        path = os.path.join(OUT, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        body = "".join(f'#include "{t}"\n' for t in targets)
        with open(path, "w") as f:
            f.write("// Generated by forever/tools/gen_compat_headers.py. Do not edit.\n"
                    "// The Turtle core's path for this header; ForeverCore has it here:\n#pragma once\n" + body)
        written.append(name)

    clashes = sorted(n for n in our_names if n in core_headers and n.endswith(".h"))
    print(f"written {len(written)}  unmapped {len(unmapped)}  unknown {len(unknown)}")
    if unknown:
        print("UNKNOWN (add to RENAMED or UNMAPPED):", unknown)
    if clashes:
        print("SAME FILE NAME IN BOTH TREES (include-order risk):", clashes)


if __name__ == "__main__":
    main()
